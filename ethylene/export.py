"""Quantise the trained MLP to int8 and write the Mega firmware weights header.

``python -m ethylene.export`` regenerates ``firmware/ethylene_mega/model_weights.h`` from ``artifacts/``.
``quantized_forward`` mirrors the sketch's arithmetic (standardise, per-row int8 dot product, scale,
bias, ReLU on hidden layers) in float32.

Layout notes: tables are flat row-major ``[out][in]``; layer 2 (128 x 256 = 32768 values) is split in two
halves ``W2A``/``W2B`` of 64 output rows each because AVR array indices are 16-bit.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch
from torch import nn

from ethylene.data import Scaler

HEADER_PATH = Path(__file__).resolve().parent.parent / "firmware" / "ethylene_mega" / "model_weights.h"
LAYER_OUT = (256, 128, 64, 32, 1)
W2_SPLIT = 64  # output rows in W2A


@dataclass
class QuantizedMLP:
    W: list[np.ndarray]  # int8, shape (out, in)
    S: list[np.ndarray]  # float32, per-output-row scale, shape (out,)
    B: list[np.ndarray]  # float32 biases, shape (out,)
    mean: np.ndarray     # float32 (6,)
    std: np.ndarray      # float32 (6,)


def quantize_mlp(model: nn.Module, scaler: Scaler) -> QuantizedMLP:
    """Symmetric per-output-row int8 quantisation of every Linear layer."""
    W, S, B = [], [], []
    for layer in (m for m in model.modules() if isinstance(m, nn.Linear)):
        w = layer.weight.detach().cpu().numpy().astype(np.float32)
        scale = np.abs(w).max(axis=1) / 127.0
        scale = np.where(scale > 0, scale, 1.0).astype(np.float32)
        W.append(np.clip(np.rint(w / scale[:, None]), -127, 127).astype(np.int8))
        S.append(scale)
        B.append(layer.bias.detach().cpu().numpy().astype(np.float32))
    return QuantizedMLP(W, S, B, np.asarray(scaler.mean, dtype=np.float32), np.asarray(scaler.std, dtype=np.float32))


def quantized_forward(q: QuantizedMLP, x_raw: np.ndarray) -> float:
    """Ripeness index for one raw 6-vector, using the firmware's arithmetic (float32)."""
    a = (np.asarray(x_raw, dtype=np.float32) - q.mean) / q.std
    last = len(q.W) - 1
    for i, (w, s, b) in enumerate(zip(q.W, q.S, q.B)):
        a = (w.astype(np.float32) @ a) * s + b
        if i != last:
            a = np.maximum(a, np.float32(0))
    return float(a[0])


def flash_bytes(q: QuantizedMLP) -> int:
    return sum(w.size for w in q.W) + 4 * sum(s.size + b.size for s, b in zip(q.S, q.B)) + 4 * (q.mean.size + q.std.size)


def _float_literal(v: float) -> str:
    text = f"{float(v):.9g}"
    if not any(c in text for c in ".en"):
        text += ".0"
    return text + "f"


def _array(ctype: str, name: str, values: np.ndarray) -> str:
    flat = values.reshape(-1)
    fmt = (lambda v: str(int(v))) if ctype == "int8_t" else _float_literal
    items = [fmt(v) for v in flat]
    rows = [", ".join(items[i:i + 16]) for i in range(0, len(items), 16)]
    body = ",\n  ".join(rows)
    return f"const {ctype} {name}[{len(items)}] PROGMEM = {{\n  {body}\n}};\n"


def write_header(q: QuantizedMLP, path: str | Path = HEADER_PATH) -> None:
    parts = [
        "// GENERATED by `python -m ethylene.export` from artifacts/ — do not edit by hand.\n"
        "// Per-row int8 weights (row-major [out][in]), float row scales and biases, input standardisation.\n"
        "// Forward: a0 = (x - SCALER_MEAN) / SCALER_STD; a_out[j] = (sum_i W[j*in+i]*a_in[i]) * S[j] + B[j];\n"
        "// ReLU after layers 1-4, none after layer 5. W2 is split into W2A (rows 0..63) and W2B (rows 64..127).\n"
        "#ifndef ETHYLENE_MODEL_WEIGHTS_H\n#define ETHYLENE_MODEL_WEIGHTS_H\n\n"
        "#include <stdint.h>\n#include <avr/pgmspace.h>\n\n"
        "#define MLP_IN 6\n#define MLP_L1 256\n#define MLP_L2 128\n#define MLP_L3 64\n#define MLP_L4 32\n#define MLP_OUT 1\n\n"
    ]
    w2 = q.W[1]
    weights = {"W1": q.W[0], "W2A": w2[:W2_SPLIT], "W2B": w2[W2_SPLIT:], "W3": q.W[2], "W4": q.W[3], "W5": q.W[4]}
    for name, arr in weights.items():
        parts.append(_array("int8_t", name, arr))
    for i in range(5):
        parts.append(_array("float", f"S{i + 1}", q.S[i]))
    for i in range(5):
        parts.append(_array("float", f"B{i + 1}", q.B[i]))
    parts.append(_array("float", "SCALER_MEAN", q.mean))
    parts.append(_array("float", "SCALER_STD", q.std))
    parts.append("\n#endif\n")
    Path(path).write_text("".join(parts), encoding="utf-8", newline="\n")


_ARRAY_RE = re.compile(r"const\s+(int8_t|float)\s+(\w+)\[[^\]]*\]\s+PROGMEM\s*=\s*\{([^}]*)\};")


def read_header(path: str | Path = HEADER_PATH) -> QuantizedMLP:
    tables: dict[str, np.ndarray] = {}
    for ctype, name, body in _ARRAY_RE.findall(Path(path).read_text(encoding="utf-8")):
        cells = [c.strip().rstrip("f") if ctype == "float" else c.strip() for c in body.split(",") if c.strip()]
        tables[name] = np.array(cells, dtype=np.int8 if ctype == "int8_t" else np.float32)
    ins = (6, 256, 128, 64, 32)
    flat_w = [tables["W1"], np.concatenate([tables["W2A"], tables["W2B"]]), tables["W3"], tables["W4"], tables["W5"]]
    W = [w.reshape(out, n_in) for w, out, n_in in zip(flat_w, LAYER_OUT, ins)]
    return QuantizedMLP(
        W, [tables[f"S{i}"] for i in range(1, 6)], [tables[f"B{i}"] for i in range(1, 6)],
        tables["SCALER_MEAN"], tables["SCALER_STD"],
    )


def main(artifacts_dir: str = "artifacts", header: str | Path = HEADER_PATH) -> None:
    from ethylene import train  # local import: keeps `export` importable without running training code

    art = train.load_artifacts(artifacts_dir)
    q = quantize_mlp(art.mlp, art.scaler)
    write_header(q, header)
    _, _, test = train.make_splits()
    x = test.X[:2000]
    with torch.no_grad():
        ref = art.mlp(torch.as_tensor(art.scaler.transform(x))).numpy()
    got = np.array([quantized_forward(q, row) for row in x])
    err = np.abs(got - ref)
    print(f"wrote {header} ({flash_bytes(q)} bytes of tables); int8 vs float32 |err|: mean {err.mean():.5f}, max {err.max():.5f}")


if __name__ == "__main__":
    main()
